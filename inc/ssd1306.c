static void write_cmd(ssd1306_t *ssd, uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd};
    i2c_write_blocking(ssd->i2c, ssd->address, buf, 2, false);
}

void ssd1306_init(ssd1306_t *ssd, uint8_t width, uint8_t height, uint8_t address, i2c_inst_t *i2c) {
    ssd->width = width;
    ssd->height = height;
    ssd->pages = height / 8;
    ssd->address = address;
    ssd->i2c = i2c;

    uint8_t cmds[] = {
        0xAE,        // Display OFF
        0xD5, 0x80,  // Set display clock
        0xA8, height - 1, // Set multiplex ratio
        0xD3, 0x00,  // Display offset = 0
        0x40,        // Start line = 0
        0x8D, 0x14,  // Enable charge pump
        0x20, 0x00,  // Memory addressing mode: Horizontal
        0xA1,        // Segment remap
        0xC8,        // COM scan direction
        0xDA, 0x12,  // COM pins hardware configuration para 128x64
        0x81, 0xCF,  // Set contrast
        0xD9, 0xF1,  // Pre-charge period
        0xDB, 0x40,  // VCOMH deselect level
        0xA4,        // Output follows RAM
        0xA6,        // Normal display
        0xAF         // Display ON
    };

    for (size_t i = 0; i < sizeof(cmds); i++) {
        write_cmd(ssd, cmds[i]);
    }
    ssd1306_fill(ssd, false);
    ssd1306_send_data(ssd);
}

void ssd1306_fill(ssd1306_t *ssd, bool value) {
    memset(ssd->buffer, value ? 0xFF : 0x00, sizeof(ssd->buffer));
}

void ssd1306_draw_pixel(ssd1306_t *ssd, uint8_t x, uint8_t y, bool value) {
    if (x >= ssd->width || y >= ssd->height) return;
    uint16_t index = x + (y / 8) * ssd->width;
    if (value)
        ssd->buffer[index] |= (1 << (y % 8));
    else
        ssd->buffer[index] &= ~(1 << (y % 8));
}

void ssd1306_send_data(ssd1306_t *ssd) {
    for (uint8_t page = 0; page < ssd->pages; page++) {
        write_cmd(ssd, 0xB0 + page);
        write_cmd(ssd, 0x00);
        write_cmd(ssd, 0x10);

        uint8_t temp[SSD1306_WIDTH + 1];
        temp[0] = 0x40;
        memcpy(&temp[1], &ssd->buffer[page * ssd->width], ssd->width);
        i2c_write_blocking(ssd->i2c, ssd->address, temp, ssd->width + 1, false);
    }
}

void ssd1306_draw_string(ssd1306_t *ssd, uint8_t x, uint8_t y, const char *str) {
    while (*str) {
        char c = *str;
        if (c >= ' ' && c <= 'Z') {
            int idx = (c - ' ') * 5;
            for (int col = 0; col < 5; col++) {
                uint8_t line = font5x7[idx + col];
                for (int bit = 0; bit < 8; bit++) {
                    ssd1306_draw_pixel(ssd, x + col, y + bit, (line >> bit) & 0x01);
                }
            }
        }
        x += 6;
        str++;
    }
}
